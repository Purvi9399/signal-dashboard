"""Synthetic plan_item injector.

TodoWrite / ExitPlanMode are interactive-only and model-discretionary, so
plan_item can't be force-generated by automated agent runs. This emits
realistic TodoWrite PostToolUse RawEvents (same envelope the hooks collector
produces) so plan_item/plan_status populate deterministically for the demo.

The curation layer (signal_curate.extract_claude_hook) already maps
TodoWrite tool_input.todos -> plan_item/plan_status.

Usage:
    python -m package.synthetic_plan_inject --sessions 5 --out /tmp/plan.jsonl
    python -m package.cli upload-jsonl /tmp/plan.jsonl
"""
from __future__ import annotations
import argparse, json, uuid
from datetime import datetime, timezone, timedelta

# A few realistic enterprise-dev plans (content, activeForm)
PLANS = [
    [("Scaffold the Flask app skeleton", "Scaffolding the Flask app skeleton"),
     ("Implement the /api/reports endpoint", "Implementing the /api/reports endpoint"),
     ("Render the reports table and nav link", "Rendering the reports table and nav link"),
     ("Add tests and verify", "Adding tests and verifying")],
    [("Extract PaymentGateway interface", "Extracting PaymentGateway interface"),
     ("Migrate Stripe provider", "Migrating Stripe provider"),
     ("Migrate PayPal provider", "Migrating PayPal provider"),
     ("Run integration suite", "Running integration suite")],
    [("Reproduce the failing auth test", "Reproducing the failing auth test"),
     ("Patch the token refresh logic", "Patching the token refresh logic"),
     ("Re-run and confirm green", "Re-running and confirming green")],
    [("Audit dependencies for CVEs", "Auditing dependencies for CVEs"),
     ("Bump vulnerable packages", "Bumping vulnerable packages"),
     ("Regenerate lockfile", "Regenerating lockfile"),
     ("Smoke-test the build", "Smoke-testing the build")],
    [("Design the Comments data model", "Designing the Comments data model"),
     ("Implement CRUD routes", "Implementing CRUD routes"),
     ("Write route tests", "Writing route tests")],
]


def _ev(ts, session, payload):
    return {"timestamp": ts, "collector_id": "claude-code.hooks",
            "agent": "claude-code", "raw_payload": payload}


def emit_session(base: datetime, idx: int):
    plan = PLANS[idx % len(PLANS)]
    session = f"synthetic-plan-{idx:03d}"
    cwd = f"/work/enterprise/app-{idx:03d}"
    events = []
    t = 0.0
    events.append(_ev((base + timedelta(seconds=t)).isoformat(), session,
                      {"hook_event_name": "SessionStart", "session_id": session,
                       "cwd": cwd, "model": "claude-sonnet-4-20250514", "version": "2.1.204",
                       "gitBranch": "main"}))
    # progressive TodoWrite snapshots: each marks the next item in_progress / completed
    for i in range(len(plan)):
        t += 20
        todos = []
        for j, (content, active) in enumerate(plan):
            status = "completed" if j < i else ("in_progress" if j == i else "pending")
            todos.append({"content": content, "activeForm": active, "status": status})
        events.append(_ev((base + timedelta(seconds=t)).isoformat(), session,
                          {"hook_event_name": "PostToolUse", "tool_name": "TodoWrite",
                           "session_id": session, "tool_use_id": f"toolu_{uuid.uuid4().hex[:16]}",
                           "cwd": cwd, "version": "2.1.204", "gitBranch": "main",
                           "tool_input": {"todos": todos},
                           "tool_response": {"oldTodos": [], "newTodos": todos}}))
    return events


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sessions", type=int, default=5)
    ap.add_argument("--out", required=True)
    ap.add_argument("--base-ts", default=None, help="ISO base timestamp (default: now)")
    args = ap.parse_args()
    base = datetime.fromisoformat(args.base_ts) if args.base_ts else datetime.now(timezone.utc)
    lines = []
    for i in range(args.sessions):
        for e in emit_session(base + timedelta(minutes=i), i):
            lines.append(json.dumps(e))
    with open(args.out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {len(lines)} events across {args.sessions} sessions to {args.out}")


if __name__ == "__main__":
    main()
