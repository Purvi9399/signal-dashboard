"""CI/CD Phase 2 helpers: Win32 detect pin render + staging layout.

See package/CICD.md. Keep McCabe ≤ 5 per function.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import sys
from pathlib import Path
from typing import Any, Mapping

_DIGEST_RE = re.compile(r"^[0-9a-f]{16}$")


def render_win32_detect_ps1(digest: str, tracked_files: int) -> str:
    """Render Intune Win32 custom detection script pinned to digest."""
    if _DIGEST_RE.fullmatch(digest) is None:
        raise ValueError(f"invalid digest {digest!r}; expected 16 lowercase hex chars")
    if tracked_files < 1:
        raise ValueError(f"tracked_files must be >= 1, got {tracked_files!r}")
    return f"""# Project Signal — Intune Win32 custom detection script
# Generated by package/package_release.py — pin matches release version.json.
#
# Exit 0 = installed and digest matches. Exit 1 = not detected.
# IMPORTANT: global --json must precede the subcommand.

$ErrorActionPreference = "Stop"

$InstallPath      = "C:\\Program Files\\ProjectSignal\\signal-agent.exe"
$ExpectedDigest   = "{digest}"
$ExpectedTracked  = {int(tracked_files)}

if (-not (Test-Path -LiteralPath $InstallPath)) {{
    exit 1
}}

try {{
    $jsonLines = & $InstallPath --json version 2>$null
    if ($LASTEXITCODE -ne 0) {{
        exit 1
    }}

    $raw = ($jsonLines | Out-String).Trim()
    if ([string]::IsNullOrWhiteSpace($raw)) {{
        exit 1
    }}

    $data = $raw | ConvertFrom-Json

    if ($data.digest -ne $ExpectedDigest) {{
        exit 1
    }}
    if ($data.tracked_files -ne $ExpectedTracked) {{
        exit 1
    }}

    Write-Output "detected digest=$ExpectedDigest tracked=$ExpectedTracked"
    exit 0
}}
catch {{
    exit 1
}}
"""


def stage_win32_dir(
    *,
    exe_path: Path,
    install_ps1: Path,
    uninstall_ps1: Path,
    detect_ps1: Path,
    out_dir: Path,
) -> None:
    """Assemble IntuneWinAppUtil -c folder contents."""
    out_dir.mkdir(parents=True, exist_ok=True)
    shutil.copy2(exe_path, out_dir / "signal-agent.exe")
    shutil.copy2(install_ps1, out_dir / "install.ps1")
    shutil.copy2(uninstall_ps1, out_dir / "uninstall.ps1")
    shutil.copy2(detect_ps1, out_dir / "detect.ps1")


def write_detect_from_version_json(version_json: Path, out_path: Path) -> None:
    """Write detect.ps1 from a version.json / platform version payload."""
    data: Mapping[str, Any] = json.loads(version_json.read_text(encoding="utf-8"))
    script = render_win32_detect_ps1(str(data["digest"]), int(data["tracked_files"]))
    out_path.write_text(script, encoding="utf-8")


def _cmd_write_detect(args: argparse.Namespace) -> int:
    write_detect_from_version_json(Path(args.version_json), Path(args.out))
    print(args.out)
    return 0


def _cmd_stage_win32(args: argparse.Namespace) -> int:
    stage_win32_dir(
        exe_path=Path(args.exe),
        install_ps1=Path(args.install_ps1),
        uninstall_ps1=Path(args.uninstall_ps1),
        detect_ps1=Path(args.detect_ps1),
        out_dir=Path(args.out_dir),
    )
    print(args.out_dir)
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="package_release")
    sub = parser.add_subparsers(dest="cmd", required=True)

    p_det = sub.add_parser("write-detect", help="render detect.ps1 from version JSON")
    p_det.add_argument("--version-json", required=True)
    p_det.add_argument("--out", required=True)
    p_det.set_defaults(func=_cmd_write_detect)

    p_stage = sub.add_parser("stage-win32", help="assemble Win32 staging folder")
    p_stage.add_argument("--exe", required=True)
    p_stage.add_argument("--install-ps1", required=True)
    p_stage.add_argument("--uninstall-ps1", required=True)
    p_stage.add_argument("--detect-ps1", required=True)
    p_stage.add_argument("--out-dir", required=True)
    p_stage.set_defaults(func=_cmd_stage_win32)

    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        return int(args.func(args))
    except (OSError, ValueError, KeyError, json.JSONDecodeError, TypeError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
