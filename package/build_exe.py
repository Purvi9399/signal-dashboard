"""
Freezes package/cli.py into a single-file, standalone executable using
PyInstaller.

WHY PYINSTALLER: it's the standard, actively-maintained tool for freezing
a Python program (interpreter + this package's own modules + any real
third-party deps -- there are currently none, this package uses only the
standard library) into one binary an end-user machine does not need a
Python install to run. That's the actual requirement for "deploy on
enterprise devices via Intune/Jamf" -- MDM tools push binaries/installers,
not source trees + a Python runtime.

HONEST LIMITATION -- NO CROSS-COMPILATION: PyInstaller does not
cross-compile. Running this script on macOS produces a macOS binary;
running it on Windows produces a Windows .exe; running it on Linux
produces a Linux binary. A real multi-platform rollout (Intune targets
Windows, Jamf targets macOS) requires running this exact script once per
target OS -- typically via CI matrix build (e.g. GitHub Actions with
windows-latest/macos-latest runners), not attempted here since this
machine can only build for itself. This is stated plainly rather than
pretending a single build here covers every target platform.

Usage:
    python3 package/build_exe.py

Produces (relative to this file's parent, i.e. collector_framework/):
    dist/signal-agent           (the frozen executable for THIS platform)
    build/                      (PyInstaller's intermediate build artifacts)
    signal-agent.spec           (the generated spec file, safe to commit
                                  and hand-edit for future builds)
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

COLLECTOR_FRAMEWORK_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(COLLECTOR_FRAMEWORK_ROOT))


def _bake_version() -> None:
    """Computes the real source tree's manifest digest right now (from the
    actual on-disk files being frozen) and writes it into a plain Python
    module PyInstaller will bundle. This is what makes `signal-agent
    version` report something real once frozen, instead of nothing --
    see cli.py's FROZEN handling for why a frozen exe can't self-snapshot
    its own (embedded, not on-disk) modules at runtime."""
    from update.update_engine import UpdateEngine

    manifest = UpdateEngine().snapshot(COLLECTOR_FRAMEWORK_ROOT)
    baked_path = COLLECTOR_FRAMEWORK_ROOT / "package" / "_baked_version.py"
    baked_path.write_text(
        f'"""Auto-generated by build_exe.py at build time. Do not hand-edit."""\n'
        f'BAKED_VERSION_DIGEST = {manifest.digest()!r}\n'
        f'BAKED_TRACKED_FILES = {len(manifest.files)!r}\n'
    )
    print(f"Baked version digest {manifest.digest()} ({len(manifest.files)} files) into {baked_path}")


def main() -> int:
    _bake_version()

    cli_entry = COLLECTOR_FRAMEWORK_ROOT / "package" / "cli.py"
    sample_policy = COLLECTOR_FRAMEWORK_ROOT / "policy" / "sample_policy.json"

    add_data_sep = ";" if sys.platform.startswith("win") else ":"

    cmd = [
        sys.executable,
        "-m",
        "PyInstaller",
        "--name",
        "signal-agent",
        "--onefile",
        "--console",
        "--paths",
        str(COLLECTOR_FRAMEWORK_ROOT),
        # Ship the sample policy alongside the exe so `signal-agent decide`
        # / `run` work out of the box with no extra files to copy manually.
        "--add-data",
        f"{sample_policy}{add_data_sep}policy",
        # discovery_engine.py loads every one of the 28 collector classes
        # via importlib.import_module() with a dynamically-built module
        # name string (see AGENT_TECHNIQUE_COLLECTORS) -- PyInstaller's
        # static import-graph analysis cannot see through that, so without
        # this flag the whole `collectors` package is silently left out of
        # the frozen bundle (confirmed by actually running the first build
        # of this exe: `decide`/`run` failed with
        # "ModuleNotFoundError: No module named 'collectors'").
        "--collect-submodules",
        "collectors",
        str(cli_entry),
    ]

    print("Running:", " ".join(cmd))
    result = subprocess.run(cmd, cwd=str(COLLECTOR_FRAMEWORK_ROOT))
    if result.returncode != 0:
        return result.returncode

    dist_bin = COLLECTOR_FRAMEWORK_ROOT / "dist" / ("signal-agent.exe" if sys.platform.startswith("win") else "signal-agent")
    print()
    print(f"Built: {dist_bin}")
    print(f"Platform: {sys.platform}")
    print("Run it with e.g.:")
    print(f"  {dist_bin} scan")
    print(f"  {dist_bin} run --live")
    return 0


if __name__ == "__main__":
    sys.exit(main())
